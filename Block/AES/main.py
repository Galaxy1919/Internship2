INV_SBOX = [0]*256
for i, v in enumerate(SBOX): INV_SBOX[v] = i
RCON = [0,1,2,4,8,16,32,64,128,27,54]

def xor(a,b): return bytes(x^y for x,y in zip(a,b))
def xtime(x): return ((x<<1)^ (0x11b if x&0x80 else 0)) & 255
def gm(a,b):
    r=0
    while b:
        if b&1:r^=a
        a=xtime(a); b>>=1
    return r

def expand(key):
    if len(key)!=16: raise ValueError('AES-128 密钥必须是16字节')
    w=[list(key[i:i+4]) for i in range(0,16,4)]
    for i in range(4,44):
        t=w[i-1][:]
        if i%4==0:
            t=t[1:]+t[:1]; t=[SBOX[x] for x in t]; t[0]^=RCON[i//4]
        w.append([w[i-4][j]^t[j] for j in range(4)])
    return [bytes(sum(w[4*r:4*r+4],[])) for r in range(11)]

def sub(s): return bytes(SBOX[x] for x in s)
def isub(s): return bytes(INV_SBOX[x] for x in s)
def shift(s):
    # 状态按列存储；第 r 行向左移动 r 个字节
    return bytes(s[4*((c+r)%4)+r] for c in range(4) for r in range(4))
def ishift(s):
    return bytes(s[4*((c-r)%4)+r] for c in range(4) for r in range(4))
def mix(s):
    out=[]
    for c in range(4):
        a=s[4*c:4*c+4]; out += [gm(a[0],2)^gm(a[1],3)^a[2]^a[3], a[0]^gm(a[1],2)^gm(a[2],3)^a[3], a[0]^a[1]^gm(a[2],2)^gm(a[3],3), gm(a[0],3)^a[1]^a[2]^gm(a[3],2)]
    return bytes(out)
def imix(s):
    out=[]
    for c in range(4):
        a=s[4*c:4*c+4]; out += [gm(a[0],14)^gm(a[1],11)^gm(a[2],13)^gm(a[3],9),gm(a[0],9)^gm(a[1],14)^gm(a[2],11)^gm(a[3],13),gm(a[0],13)^gm(a[1],9)^gm(a[2],14)^gm(a[3],11),gm(a[0],11)^gm(a[1],13)^gm(a[2],9)^gm(a[3],14)]
    return bytes(out)

def encrypt_block(p,key, trace=False):
    if len(p)!=16: raise ValueError('AES 分组必须是16字节')
    rk=expand(key); s=xor(p,rk[0]); logs=[s]
    for r in range(1,11):
        s=xor(mix(shift(sub(s))) if r<10 else shift(sub(s)),rk[r]); logs.append(s)
    return (s,logs) if trace else s

def decrypt_block(c,key):
    if len(c)!=16: raise ValueError('AES 分组必须是16字节')
    rk=expand(key); s=xor(c,rk[10])
    for r in range(9,0,-1):
        s=ishift(isub(s)); s=imix(xor(s,rk[r]))
    return xor(isub(ishift(s)),rk[0])
def pad(data): n=16-len(data)%16; return data+bytes([n])*n
def unpad(data):
    n=data[-1]
    if not 1<=n<=16 or data[-n:]!=bytes([n])*n: raise ValueError('填充校验失败：密钥或密文可能错误')
    return data[:-n]
def encrypt(data,key): return b''.join(encrypt_block(p,key) for p in (pad(data)[i:i+16] for i in range(0,len(pad(data)),16)))
def decrypt(data,key):
    if len(data)%16: raise ValueError('密文长度必须是16的倍数')
    return unpad(b''.join(decrypt_block(data[i:i+16],key) for i in range(0,len(data),16)))
def avalanche_demo(p,key):
    c,t=encrypt_block(p,key,True); q=bytearray(p); q[0]^=1; c2,t2=encrypt_block(bytes(q),key,True)
    return c,c2,[sum((a^b).bit_count() for a,b in zip(x,y)) for x,y in zip(t,t2)]

